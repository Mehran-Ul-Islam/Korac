import re

PURPLE_GRAD = re.compile(
    r"(from|via|to)-(purple|violet|fuchsia|indigo)-\d+"
    r"|linear-gradient\([^)]*(purple|violet|#(?:6366f1|7c3aed|8b5cf6|a855f7|9333ea|6d28d9))",
    re.I,
)
DARK_BG = re.compile(
    r"bg-(black|slate-9\d\d|gray-9\d\d|zinc-9\d\d|neutral-9\d\d)"
    r"|background(-color)?:\s*(#0\w{5}|#000\b|black)",
    re.I,
)
GENERATED = ("auto-generated", "autogenerated", "do not edit", "@generated")
WEB = ("tsx", "ts", "jsx", "js", "html", "css")
MACRO = re.compile(r"\{\{.*?\}\}", re.S)


def slop(text):
    return bool(PURPLE_GRAD.search(text)) and bool(DARK_BG.search(text))


def keep(name, text):
    n = len(text)
    if name == "design":
        return n > 50
    if name in ("wiki", "docs"):
        return n > 200
    if n < 300 or n > 12000:
        return False
    if max(len(l) for l in text.split("\n")) > 300:
        return False
    if any(g in text[:500].lower() for g in GENERATED):
        return False
    if name in ("tsx", "jsx") and not ("react" in text and ("</" in text or "/>" in text)):
        return False
    if name == "ts" and "react" in text and ("</" in text or "/>" in text):
        return False
    if name in WEB and slop(text):
        return False
    return True

def clean_doc(text):
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            text = text[end + 4:]
    return MACRO.sub("", text).strip()
